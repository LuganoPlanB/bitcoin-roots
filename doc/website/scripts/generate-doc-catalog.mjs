import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(siteRoot, "../..");
const outputPath = join(siteRoot, ".vitepress", "generated", "catalog.mjs");

const excludedDirectories = new Set([
  ".git",
  ".gestalt",
  ".github",
  ".impeccable",
  ".vitepress",
  "node_modules",
  "releases",
  "upstream",
]);

const excludedFiles = new Set([
  "AGENTS.md",
  "DESIGN.md",
  "PRODUCT.md",
  "documentation.md",
  "getting-started.md",
  "index.md",
]);

const groupDefinitions = [
  { id: "project", label: "Project essentials", matches: (path) => !path.includes("/") },
  { id: "operations", label: "Operate a node", matches: (path) => /^doc\/(?!release-notes\/|design\/|policy\/)/.test(path) },
  { id: "policy", label: "Policy", matches: (path) => path.startsWith("doc/policy/") },
  { id: "design", label: "Architecture & design", matches: (path) => path.startsWith("doc/design/") },
  { id: "releases", label: "Release history", matches: (path) => path.startsWith("doc/release-notes/") },
  { id: "contrib", label: "Contributor tools", matches: (path) => path.startsWith("contrib/") },
  { id: "internals", label: "Components & internals", matches: (path) => path.startsWith("src/") },
  { id: "testing", label: "Testing & CI", matches: (path) => path.startsWith("test/") || path.startsWith("ci/") },
  { id: "dependencies", label: "Build dependencies", matches: (path) => path.startsWith("depends/") },
  { id: "utilities", label: "Utilities", matches: (path) => path.startsWith("share/") },
];

async function collectMarkdown(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = join(directory, entry.name);
    const projectPath = relative(repositoryRoot, absolutePath).split(sep).join("/");

    if (entry.isDirectory()) {
      if (
        excludedDirectories.has(entry.name) ||
        entry.name.startsWith("build") ||
        projectPath === "doc/website"
      ) continue;
      files.push(...await collectMarkdown(absolutePath));
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(".md") && !excludedFiles.has(entry.name)) {
      files.push(projectPath);
    }
  }

  return files;
}

function cleanTitle(value) {
  return value
    .replace(/<[^>]+>/g, "")
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[`*_~]/g, "")
    .replace(/\s+#+\s*$/, "")
    .trim();
}

function fallbackTitle(path) {
  const parts = path.split("/");
  const filename = parts.at(-1).replace(/\.md$/, "");
  const source = filename.toLowerCase() === "readme" ? parts.at(-2) ?? "Bitcoin Roots" : filename;
  return source.replace(/[-_]/g, " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function extractTitle(markdown, path) {
  let inFence = false;

  for (const line of markdown.split(/\r?\n/)) {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      continue;
    }

    if (!inFence) {
      const heading = line.match(/^#{1,3}\s+(.+)$/);
      if (heading) return cleanTitle(heading[1]) || fallbackTitle(path);
    }
  }

  return fallbackTitle(path);
}

function routeFor(path) {
  return `/${path.replace(/\.md$/, "")}`;
}

const paths = (await collectMarkdown(repositoryRoot)).sort((a, b) => a.localeCompare(b));
const documents = await Promise.all(paths.map(async (path) => ({
  path,
  link: routeFor(path),
  title: extractTitle(await readFile(join(repositoryRoot, path), "utf8"), path),
})));

const groups = groupDefinitions.map(({ id, label, matches }) => ({
  id,
  label,
  documents: documents.filter((document) => matches(document.path)),
})).filter((group) => group.documents.length > 0);

const assignedCount = groups.reduce((total, group) => total + group.documents.length, 0);
if (assignedCount !== documents.length) {
  throw new Error(`Documentation catalog assigned ${assignedCount} of ${documents.length} Markdown files.`);
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, [
  "// Generated by scripts/generate-doc-catalog.mjs. Do not edit.",
  `export const documentationGroups = ${JSON.stringify(groups, null, 2)};`,
  `export const documentationCount = ${documents.length};`,
  "",
].join("\n"));

console.log(`Cataloged ${documents.length} source documents in ${groups.length} groups.`);
